@register.filter
def thumb_seed(listing):
    """Seed for the admin's small house drawing: condos get the tall building."""
    return listing.pk * 4 + (2 if str(listing.property_type) == "Condominium" else 0)


@register.filter
def initials(user):
    """Carlos Kosala -> CK, Janet -> JA."""
    if not user:
        return ""
    first, last = (user.first_name or user.username).strip(), (user.last_name or "").strip()
    return (first[:1] + last[:1] if last else first[:2]).upper()
