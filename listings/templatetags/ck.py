@register.simple_tag
def icon(name, cls=""):
    """Inline SVG icon, hidden from screen readers (the text next to it carries the meaning)."""
    path = ICONS.get(name, ICONS["info"])
    return format_html(
        '<svg class="ic {}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" '
        'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="{}"/></svg>',
        cls,
        path,
    )


@register.filter
def money(value):
    """425000 -> $425,000"""
    try:
        return f"${round(float(value)):,}"
    except (TypeError, ValueError):
        return ""


@register.filter
def status_class(status):
    """Chip class for a listing status: av, pe or so."""
    name = str(status)
    return {"Available": "av", "Pending": "pe"}.get(name, "so")


TYPE_ICONS = {"Ranch": "home", "Tudor": "home", "Split-Entry": "layers", "Townhome": "building", "Condominium": "building"}


@register.filter
def type_icon(property_type):
    """Choose the existing icon name associated with a property type."""
    return TYPE_ICONS.get(str(property_type), "home")


@register.filter
def baths(value):
    """2.0 -> 2, 2.5 -> 2.5"""
    try:
        v = float(value)
    except (TypeError, ValueError):
        return value
    return int(v) if v == int(v) else v


